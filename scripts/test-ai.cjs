/* eslint-disable @typescript-eslint/no-require-imports -- Node CommonJS test runner */
const assert = require('node:assert/strict');
const fs = require('node:fs');
const ts = require('typescript');
const Module = require('node:module');
const path = require('node:path');
require.extensions['.ts'] = (module, filename) => module._compile(ts.transpileModule(fs.readFileSync(filename,'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText,filename);
const compiled = ts.transpileModule(fs.readFileSync('src/lib/ai.ts','utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText;
const file = path.resolve('src/lib/ai.ts');
const mod = new Module(file, module); mod.filename=file; mod.paths=Module._nodeModulePaths(path.dirname(file)); mod._compile(compiled,file);
const ai = mod.exports;
(async()=>{
  delete process.env.OPENAI_API_KEY; delete process.env.GEMINI_API_KEY;
  assert.equal(ai.resolveProvider('auto'),'local');
  assert.throws(()=>ai.resolveProvider('openai'),/NOT_CONFIGURED/);
  process.env.OPENAI_API_KEY='test-key-for-mocked-fetch-only';
  process.env.GEMINI_API_KEY='test-key-for-mocked-fetch-only';
  let body;
  global.fetch=async(url, options)=>{body=JSON.parse(options.body); return new Response(JSON.stringify({output:[{type:'message',content:[{type:'output_text',text:'Hello'}]}]}));};
  assert.equal(await ai.generateText({provider:'openai',instructions:'Tutor',messages:[{role:'user',content:'Hi'}]}),'Hello');
  assert.equal(body.store,false); assert.equal(body.input[0].content,'Hi');
  global.fetch=async(url,options)=>{body=JSON.parse(options.body);return new Response(JSON.stringify({candidates:[{content:{parts:[{text:'private thought',thought:true},{text:'Answer'}]}}]}));};
  assert.equal(await ai.generateText({provider:'gemini',instructions:'Tutor',document:{mimeType:'application/pdf',data:'JVBERi0='},json:true,messages:[{role:'assistant',content:'Earlier'},{role:'user',content:'Hi'}]}),'Answer');
  assert.equal(body.contents[0].role,'model');
  assert.equal(body.contents[1].parts[1].inlineData.mimeType,'application/pdf');
  assert.equal(body.generationConfig.responseMimeType,'application/json');
  global.fetch=async()=>new Response('{}',{status:429});
  await assert.rejects(()=>ai.generateText({provider:'openai',instructions:'',messages:[]}),/RATE_LIMITED/);
  global.fetch=async()=>new Response('{}');
  await assert.rejects(()=>ai.generateText({provider:'gemini',instructions:'',messages:[]}),/EMPTY_RESPONSE/);
  global.fetch=async()=>new Response(JSON.stringify({error:{message:'Quota exhausted',details:[{violations:[{quotaId:'GenerateRequestsPerDayPerProjectPerModel-FreeTier',quotaValue:'20'}]}]}}),{status:429});
  await assert.rejects(()=>ai.generateText({provider:'gemini',instructions:'',messages:[]}),/QUOTA_EXHAUSTED/);
  global.fetch=async(url,options)=>{body=JSON.parse(options.body);assert.match(url,/11434\/api\/chat$/);return new Response(JSON.stringify({message:{content:'Local answer'}}));};
  assert.equal(await ai.generateText({provider:'ollama',instructions:'Thai tutor',messages:[{role:'user',content:'Hi'}]}),'Local answer');
  assert.equal(body.stream,false);assert.equal(body.messages[0].role,'system');assert.equal(body.model,'llama3.2:3b');
  global.fetch=async()=>{throw new TypeError('fetch failed');};
  await assert.rejects(()=>ai.generateText({provider:'ollama',instructions:'',messages:[]}),/OLLAMA_OFFLINE/);
  let calls=0;
  global.fetch=async()=>++calls===1?new Response('{}',{status:503}):new Response(JSON.stringify({candidates:[{content:{parts:[{text:'Recovered'}]}}]}));
  assert.equal(await ai.generateText({provider:'gemini',instructions:'',messages:[{role:'user',content:'Hi'}]}),'Recovered');
  assert.equal(calls,2);
  global.fetch=async()=>new Response('{}',{status:403});
  await assert.rejects(()=>ai.generateText({provider:'gemini',instructions:'',messages:[]}),/INVALID_KEY/);
  global.fetch=async()=>new Response('{}',{status:404});
  await assert.rejects(()=>ai.generateText({provider:'gemini',instructions:'',messages:[]}),/MODEL_UNAVAILABLE/);
  for(let i=0;i<30;i++)assert.equal(ai.allowAIRequest('test-user'),true);
  assert.equal(ai.allowAIRequest('test-user'),false);
  console.log('PASS: provider fallback, missing keys, OpenAI/Gemini response parsing, conversation roles, rate-limit and empty-response handling. No external API calls.');
})().catch(e=>{console.error(e);process.exitCode=1});
